import { ArrowRight, Boxes, FileArchive, KeyRound, ListChecks } from "lucide-react";
import Link from "next/link";
import type { ReactNode } from "react";
import { listAccessReviews } from "@/platform/access-reviews";
import { accessMatrix } from "@/platform/admin";
import { requirePagePermission } from "@/platform/auth";
import { db } from "@/platform/db";
import { hasPermission } from "@/platform/rbac";
import { RelativeTime } from "@/platform/ui/RelativeTime";
import { StatCards } from "@/platform/ui/StatCards";
import { tools } from "@/tools";
import { ADMIN_SECTIONS } from "./sections";

const ICONS: Record<string, ReactNode> = {
  "/admin/tools": <Boxes />,
  "/admin/access": <KeyRound />,
  "/admin/access-reviews": <ListChecks />,
  "/admin/evidence": <FileArchive />,
};

export default async function AdminOverview() {
  const user = await requirePagePermission("admin:read");
  const [userCount, reviews, lastExport] = await Promise.all([
    db.user.count(),
    listAccessReviews(),
    db.auditEvent.findFirst({ where: { action: "evidence.export" }, orderBy: { createdAt: "desc" } }),
  ]);
  const matrix = accessMatrix();
  const grants = matrix.roles.reduce((n, r) => n + matrix.grants[r].size, 0);
  const current = reviews.find((r) => r.status === "in_progress");
  const lastDone = reviews.find((r) => r.status === "completed");

  return (
    <div className="space-y-6">
      <StatCards
        items={[
          { label: "Tools", value: tools.length, hint: "in the registry" },
          { label: "Users", value: userCount, hint: `${matrix.roles.length} roles, ${grants} grants` },
          {
            label: "Access review",
            value: current ? `${current.summary.decided}/${current.summary.total}` : lastDone ? "Done" : "None",
            hint: current ? `${current.name}, in progress` : lastDone?.completedAt ? <>Last completed <RelativeTime date={lastDone.completedAt} /></> : "No review yet",
          },
          {
            label: "Evidence pack",
            value: lastExport ? <RelativeTime date={lastExport.createdAt} /> : "Never",
            hint: lastExport ? `last generated by ${lastExport.actorName}` : "not generated yet",
          },
        ]}
      />
      <div className="grid grid-cols-1 gap-3 sm:grid-cols-2">
        {ADMIN_SECTIONS.filter((s) => hasPermission(user, s.permission)).map((s) => (
          <Link key={s.href} href={s.href} className="group rounded-lg border bg-card p-4 transition-colors hover:border-primary/40 hover:bg-muted/30">
            <div className="flex items-center gap-2">
              <div className="flex size-8 items-center justify-center rounded-md bg-primary/10 text-primary [&_svg]:size-4">{ICONS[s.href]}</div>
              <p className="text-sm font-medium">{s.label}</p>
              <ArrowRight className="ml-auto size-4 text-muted-foreground opacity-0 transition-opacity group-hover:opacity-100" />
            </div>
            <p className="mt-2 text-sm text-muted-foreground">{s.description}</p>
          </Link>
        ))}
      </div>
    </div>
  );
}
